"""Everything the model reads, and how its answer is read back.

The model receives only the schema of the synthetic data (names, types, possible values) and the question: no
row, no statistic. Its answer is one Python code block that draws a chart and leaves its numbers in a ``summary``
table (computed and shown locally), followed by a short explanation, or plain text alone when the question cannot
or must not be answered with a chart.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass

from sds.llm_analyst.errors import INCOMPLETE_ANSWER, AnalystError
from sds.llm_analyst.llm_config import MAX_ERROR_CHARS

# Measured on 10 questions about a medical and a census dataset: 8/8 correct charts, 2 correct refusals,
# no failed code. Changing it means measuring again.
SYSTEM_PROMPT_TEMPLATE = """You are a data analyst helping a person who cannot program. The data are SYNTHETIC: rows
generated by a model that imitates a real dataset, so no row is a real person. A pandas DataFrame called `df` is
already loaded. Its columns (name, type, possible values) are:
{schema}
The possible values are listed in alphabetical order, which is not always their natural order.

Answer with ONE Python code block that uses only pandas and matplotlib.pyplot (already imported as `pd` and
`plt`) and draws exactly one chart:
- create the figure once with `fig, ax = plt.subplots(...)` and draw on `ax` (pass `ax=ax` to pandas plots);
- choose the chart that answers best: scatter plots, histograms, box plots, counts, shares and averages are all
  fine;
- when categories have a natural order (levels of education, age bands, months...), show them in that order,
  otherwise sort them by the plotted value;
- keep labels readable: rotate long category labels only when needed and call `fig.tight_layout()`;
- also put the numbers the chart shows in a small pandas DataFrame or Series called `summary` (counts, shares,
  averages or quantiles per group, a correlation...), rounded to 2 decimals, with clear column names and at most
  20 rows; never single records; do not print anything.
Do not read or write files and do not call plt.show().
After the code block write at most two plain sentences, in the language of the question, explaining how to
read the chart. You cannot see the data: never state numbers or results.

Write no code, and answer in one or two plain sentences in the language of the question, when:
- the columns cannot answer the question: say which information is missing;
- the question asks for single records (a specific person, the oldest person, some rows): explain that the rows
  are invented by the model and describe no real person, and suggest a question about a distribution instead."""

FIX_REQUEST_TEMPLATE = "Your code could not be run. Error: {error}\nFix the code and answer again in the same format."

COMPLETE_FINISH_REASON = "stop"
FENCE = "```"
CODE_TAGS = {"python", "py", ""}
# A fenced block: the tag on the opening line, then everything up to the closing fence.
BLOCK = re.compile(r"```[ \t]*([A-Za-z0-9_+-]*)[ \t]*\r?\n(.*?)```", re.DOTALL)

INCOMPLETE_MESSAGE = "The answer came back cut off or empty. Please ask again, perhaps with a simpler question."


@dataclass(frozen=True)
class Answer:
    """What the model answered.

    Attributes:
        code: The Python code to run, or ``None`` for an answer in plain text only (e.g. a refusal).
        text: The explanation, possibly empty when there is code.
    """

    code: str | None
    text: str


def system_prompt(schema: list[dict]) -> str:
    """The system prompt for a dataset.

    Args:
        schema: The columns of the synthetic data, as given by ``SchemaContract.llm_schema()``.

    Returns:
        The prompt, with one JSON object per column.
    """
    lines = "\n".join(json.dumps(column, ensure_ascii=False) for column in schema)
    return SYSTEM_PROMPT_TEMPLATE.replace("{schema}", lines)


def fix_request(error: str) -> str:
    """The message that asks the model, once, to fix code that could not be run.

    Args:
        error: Type and message of the error (no stack trace); cut to ``MAX_ERROR_CHARS``.

    Returns:
        The text of the user message to send after the model's failed answer.
    """
    return FIX_REQUEST_TEMPLATE.format(error=error[:MAX_ERROR_CHARS])


def parse_answer(content: str | None, finish_reason: str | None) -> Answer:
    """Split an answer of the model into code and explanation.

    The code is the first fenced block tagged ``python``, ``py`` or nothing; the explanation is all the text
    outside the blocks. Other blocks are dropped: only one piece of code is run and shown.

    Args:
        content: Text of the answer.
        finish_reason: Why the model stopped; only ``"stop"`` means a complete answer.

    Returns:
        The code (or ``None``) and the explanation.

    Raises:
        AnalystError: ``incomplete_answer`` when the answer was cut, filtered, empty or has an unclosed block.
    """
    content = content or ""
    if finish_reason != COMPLETE_FINISH_REASON or not content.strip() or content.count(FENCE) % 2:
        raise AnalystError(INCOMPLETE_ANSWER, INCOMPLETE_MESSAGE)
    code, pieces, start = None, [], 0
    for block in BLOCK.finditer(content):
        pieces.append(content[start:block.start()])
        start = block.end()
        if code is None and block.group(1).lower() in CODE_TAGS:
            code = block.group(2).strip()
    pieces.append(content[start:])
    text = "\n\n".join(piece.strip() for piece in pieces if piece.strip())
    return Answer(code=code, text=text)
