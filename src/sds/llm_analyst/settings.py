"""Settings of the LLM provider: any service compatible with the OpenAI API (OpenAI, Groq, ...).

Three variables, from the environment or a ``.env`` file: ``LLM_API_KEY``, ``LLM_BASE_URL`` (empty means
OpenAI) and ``LLM_MODEL``. The model is required like the key: each provider has its own model names, so the code
has no default to fall back on.

The ``.env`` file is read only when ``load_settings`` is called, never at import time, and its values are never
copied into ``os.environ``: the code generated by the model runs in a child process, which must not inherit the
key even if its environment were not cleaned.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

from sds.llm_analyst.errors import LLM_NOT_CONFIGURED, AnalystError

API_KEY_ENV = "LLM_API_KEY"
BASE_URL_ENV = "LLM_BASE_URL"
MODEL_ENV = "LLM_MODEL"


@dataclass(frozen=True)
class LlmSettings:
    """Settings of the client of an OpenAI-compatible provider.

    Attributes:
        api_key: Secret key of the provider (never logged or shown).
        model: Name of the chat model, as the provider spells it.
        base_url: Address of the provider's API; ``None`` for OpenAI.
    """

    api_key: str
    model: str
    base_url: str | None = None

    def __repr__(self) -> str:
        return f"LlmSettings(api_key='***', model={self.model!r}, base_url={self.base_url!r})"


class LlmNotConfiguredError(AnalystError):
    """Raised when a required setting is missing: the app still runs, only the question step is off.

    Attributes:
        missing: Names of the missing variables, in the order key, model.
    """

    def __init__(self, missing: tuple[str, ...]) -> None:
        super().__init__(
            LLM_NOT_CONFIGURED,
            f"{', '.join(missing)} not set: copy .env.example to .env, fill it in and restart the app.",
        )
        self.missing = missing


def load_settings(env_file: str | Path | None = None) -> LlmSettings:
    """Read the provider settings from the environment and a ``.env`` file, without changing ``os.environ``.

    Variables already set in the environment win over the file. Values are stripped; an empty value counts as
    missing.

    Args:
        env_file: Path of the ``.env`` file. ``None`` looks for one from the working folder upwards, so the app
            launched from a subfolder of the project finds the file in a parent folder.

    Returns:
        The settings of the provider.

    Raises:
        LlmNotConfiguredError: When ``LLM_API_KEY`` or ``LLM_MODEL`` is missing or empty.
    """
    from dotenv import dotenv_values, find_dotenv  # here, so that importing sds never loads dotenv

    path = find_dotenv(usecwd=True) if env_file is None else env_file
    file_values = dotenv_values(path)

    def read(name: str) -> str:
        value = os.environ[name] if name in os.environ else file_values.get(name)
        return (value or "").strip()

    api_key, model, base_url = read(API_KEY_ENV), read(MODEL_ENV), read(BASE_URL_ENV)
    missing = tuple(name for name, value in ((API_KEY_ENV, api_key), (MODEL_ENV, model)) if not value)
    if missing:
        raise LlmNotConfiguredError(missing)
    return LlmSettings(api_key=api_key, model=model, base_url=base_url or None)
